/**
 * 安装器的深色模式：跟随系统，没有设置界面（主程序有「浅色/深色/跟随系统」
 * 三档设置，安装器只有一屏安装向导，多一个开关只会多一个要维护的状态）。
 *
 * ── 先回答「Tauri 侧能不能拿到系统主题」──────────────────────────────
 *
 * 能。三条都在本机核对过（tauri 2.11.5 的源码 + @tauri-apps/api 的类型文档）：
 *   1. 窗口由 tauri.conf.json 的 app.windows[0] 创建（main.rs 的 main() 里只有
 *      tauri::Builder::default().run(generate_context!())，没有 WebviewWindowBuilder），
 *      而那个窗口配置里**没有 theme 字段** —— 按 @tauri-apps/api 的 WindowOptions
 *      文档，初始窗口主题「Defaults to the system theme」，也就是没被钉死。
 *   2. capabilities/default.json 里的 "core:default" 展开后包含
 *      "core:window:default"（tauri-2.11.5/build.rs 的 PLUGINS 里就有 core:window，
 *      core:default 逐个取 "k:default"），而 window 的默认权限集里有 allow-theme
 *      （permissions/window/autogenerated/reference.md）—— 所以
 *      getCurrentWindow().theme() 不需要新增任何权限。
 *   3. 事件侧：tauri://theme-changed（onThemeChanged）由 tao/wry 的
 *      WindowEvent::ThemeChanged 转发（tauri-2.11.5/src/window.rs:271）；
 *      注册监听走 plugin:event|listen，而 core:event:default 里有 allow-listen
 *      （permissions/event/autogenerated/reference.md），同样不用加权限。
 *
 * ── 那为什么还是以 prefers-color-scheme 为主判据 ──────────────────────
 *
 *   · 主程序在同一套 Tauri 2 + WebView2 上就是这么做的，而且已经上线：
 *     src/composables/useTheme.ts 的「跟随系统」档只读 matchMedia。
 *     这是本项目里被真实用户机器验证过的信号，不是推测。
 *   · 首帧不允许等 IPC。theme() 要一个来回，回来之前页面已经画完了 ——
 *     深色用户每次都会先看到一帧白。所以首帧由 index.html 的内联脚本
 *     同步读 matchMedia 定下来（0 次 IPC），theme() 只做补判。
 *
 * ⚠ 一条没验证到的：本机没有把安装器窗口跑起来（cargo build + 起 GUI 看窗口主题），
 *   所以「theme() 在这台机器上到底报 light 还是 dark」没有运行时确认。
 *   这也是判据取并集的原因之一 —— 不把任何一个来源当成唯一的真相。
 *
 * ── 两者不一致时取并集（任一为深色即深色）────────────────────────────
 *
 * 为什么不「以窗口主题为准」：万一 WebView2 的媒体查询被钉在浅色
 * （窗口 theme 为 None 时不是不可能），系统深色的用户会一直看白界面；
 * 窗口主题 API 是另一个来源，正好能救这一种情况。
 * 反过来，万一窗口主题误报深色，代价只是「配色没跟着系统走」。
 * 两种误判的代价不对称 —— 误判成深色只是不好看，误判成浅色是半夜被白屏闪瞎。
 * 既然离线无法判定谁错，就选代价小的那一侧。
 *
 * 拿不到 Tauri 主题时（非 Tauri 环境跑 vite dev、权限被收、IPC 失败）不报错，
 * 静默留在 matchMedia 的结果上 —— 那已经是一个能用的答案。这就是「兜底」。
 */
import { getCurrentWindow } from "@tauri-apps/api/window";
import type { UnlistenFn } from "@tauri-apps/api/event";

/** 系统是否偏好深色。老 WebView 没有 matchMedia 时按浅色。 */
function systemDark(): boolean {
  return typeof window.matchMedia === "function"
    && window.matchMedia("(prefers-color-scheme: dark)").matches;
}

/** Tauri 窗口主题的答复：true 深色 / false 浅色 / null 还没拿到。 */
let windowDark: boolean | null = null;

/** 并集判据，见文件头。 */
function resolveDark(): boolean {
  return systemDark() || windowDark === true;
}

/** 把主题写到 <html data-theme>。没有这个属性就是浅色（与主程序同一约定）。 */
function applyTheme(dark: boolean) {
  const root = document.documentElement;
  if (dark) root.setAttribute("data-theme", "dark");
  else root.removeAttribute("data-theme");
  // 原生控件（滚动条、复选框）也跟着走，否则深色下 .content 与 .eula-box
  // 两个可滚动区域会拖出一条白滚动条。tokens.css 里也有一份（样式表侧兜底），
  // 内联样式优先级更高，两者同时存在不冲突。
  root.style.colorScheme = dark ? "dark" : "light";
}

/**
 * 初始化主题，并订阅「系统切换时跟着变」。返回值用于取消订阅。
 *
 * 必须在 index.html 的内联脚本之后调用：那个脚本已经在首帧前用 matchMedia
 * 定过一次色，这里只补 IPC 侧那一路判据，以及系统切换时的实时跟随。
 */
export async function initTheme(): Promise<() => void> {
  // 内联脚本万一没跑（HTML 被外部工具改写、脚本被拦），在这里补齐，
  // 免得停在「无属性 = 浅色」上。
  if (!document.documentElement.hasAttribute("data-theme")) applyTheme(resolveDark());

  const media = typeof window.matchMedia === "function"
    ? window.matchMedia("(prefers-color-scheme: dark)")
    : null;
  const onMediaChange = () => applyTheme(resolveDark());
  media?.addEventListener("change", onMediaChange);

  let unlistenWindowTheme: UnlistenFn | null = null;
  try {
    const win = getCurrentWindow();
    const theme = await win.theme();
    if (theme === "dark" || theme === "light") {
      windowDark = theme === "dark";
      applyTheme(resolveDark());
    }
    // 系统主题变化时 tao 会发 tauri://theme-changed。它和 matchMedia 的
    // change 事件在正常机器上是同一件事的两次通知，重复调用 applyTheme 无害
    // （写的是同一个值），但少任何一路都不会漏 —— 不赌某一侧一定可靠。
    unlistenWindowTheme = await win.onThemeChanged(({ payload }) => {
      windowDark = payload === "dark";
      applyTheme(resolveDark());
    });
  } catch (e) {
    // 直接用浏览器打开 vite dev（没有 __TAURI_INTERNALS__）时 getCurrentWindow()
    // 就会抛；权限被收时 theme() 会抛。都不该打断安装向导的启动。
    console.warn("[installer] window theme unavailable, fallback to prefers-color-scheme:", e);
  }

  return () => {
    media?.removeEventListener("change", onMediaChange);
    if (unlistenWindowTheme) unlistenWindowTheme();
  };
}
